-- =============================================================
-- 修复：演示患者 patient001 收费管理页不显示「支付」按钮
-- =============================================================
-- 现象：
--   以 patient001 登录「收费管理」，操作列看不到「支付」按钮。
--
-- 根因（数据状态，非代码/权限 bug）：
--   前端 bill/index.vue 的支付按钮渲染条件为
--     v-if="row.status === 0 || row.status === '0'"
--   即【只有未支付(status=0)的账单】才显示「支付」。
--   而 patient001(id=1) 的两条账单(id=8、id=53)当前 status 都是 1(已支付)
--   —— id=53 原本是未支付，但在之前测试支付功能时被付掉了。
--   因此该患者没有待支付账单 → 按钮整列不渲染。
--   全库尚余 17 条 status=0 的账单（分布在其他患者），证明按钮逻辑与
--   bill:pay 权限均正常，仅 patient001 恰好无待支付项。
--
-- 修复：把 id=53 恢复为「未支付」，供患者支付功能演示/测试。
--   幂等：仅当 id=53 当前确为已支付(status=1)时才回滚，重复执行安全。
-- =============================================================

SET NAMES utf8mb4;
USE ruoyi_vue_pro;

UPDATE hospital_bill
SET status = 0,
    pay_amount = 0.0,
    pay_method = NULL,
    pay_time = NULL
WHERE id = 53
  AND patient_id = 1
  AND status = 1;
